// Emits cross-language canonicalization/signing vectors from the TypeScript
// implementation, which is the reference. The Python SDK asserts against
// these: a one-byte divergence in JCS output means every signature it makes
// is rejected, and that failure would otherwise surface only in production.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as ed from '@noble/ed25519';
import { canonicalize, payloadHash, requestDescriptor, sha256Hex } from '../dist/index.js';

const VALUES = [
  ['empty-object', {}],
  ['empty-array', []],
  ['null', null],
  ['true', true],
  ['string', 'hello'],
  ['key-order', { b: 1, a: 2, c: 3 }],
  ['nested-key-order', { z: { y: 1, x: 2 }, a: [{ q: 1, p: 2 }] }],
  // §3.2.3 sorts by UTF-16 code unit, so an astral character sorts BEFORE
  // U+FFFF. Python's default sort is by code point and gets this backwards.
  ['utf16-key-order', { '\uffff': 1, '\u{10000}': 2, a: 3 }],
  ['unicode-values', { text: 'héllo 日本語 👩‍💻', combining: 'e\u0301' }],
  // Deliberately NOT normalized: U+00E9 and e+U+0301 stay distinct.
  ['precomposed-vs-combining', { a: '\u00e9', b: 'e\u0301' }],
  ['control-chars', { s: 'a\u0000b\tc\nd\u001fe' }],
  ['quotes-and-backslash', { s: 'he said "hi" \\ bye and a trailing \\' }],
  ['integers', { zero: 0, one: 1, neg: -42, big: 9007199254740991 }],
  ['floats', { a: 0.1, b: 1.5, c: -2.25, d: 1e21, e: 1e-7, f: 1.0 }],
  ['nested-arrays', [1, [2, [3, [4]]]]],
  ['mixed', { ok: true, items: [1, 'two', null, { three: 3 }], when: '2026-10-20T20:50:46Z' }],
];

const canon = VALUES.map(([name, value]) => ({
  name,
  value,
  canonical: canonicalize(value),
  payload_hash: payloadHash(value),
}));

const DESCRIPTORS = [
  {
    name: 'get-inbox',
    method: 'get',
    path: '/v1/inbox',
    query: { since: 'msg_01J', limit: '50' },
    body: '',
    timestamp: '2026-10-20T20:50:46Z',
  },
  {
    name: 'post-tasks',
    method: 'POST',
    path: '/v1/tasks',
    query: {},
    body: '{"a":1}',
    timestamp: '2026-10-20T20:50:46Z',
  },
  {
    name: 'array-query',
    method: 'GET',
    path: '/v1/tasks',
    query: { state: ['working', 'accepted'], limit: '2' },
    body: '',
    timestamp: '2026-10-20T20:50:46Z',
  },
];

// A fixed key so the Python side can verify it produces byte-identical
// signatures, not merely signatures that happen to verify.
const priv = new Uint8Array(32).map((_, i) => (i * 7 + 3) % 256);
const pub = await ed.getPublicKeyAsync(priv);

const descriptors = [];
for (const d of DESCRIPTORS) {
  const descriptor = requestDescriptor(d);
  const sig = await ed.signAsync(new TextEncoder().encode(descriptor), priv);
  descriptors.push({
    ...d,
    descriptor,
    signature: `ed25519:${Buffer.from(sig).toString('base64')}`,
  });
}

const out = {
  note: 'Generated by contracts/scripts/gen-vectors.mjs. The TypeScript implementation is the reference.',
  privateKeyBase64: Buffer.from(priv).toString('base64'),
  publicKeyBase64: Buffer.from(pub).toString('base64'),
  sha256: [
    { input: '', hex: sha256Hex('') },
    { input: 'abc', hex: sha256Hex('abc') },
    { input: '👋', hex: sha256Hex('👋') },
  ],
  canonical: canon,
  descriptors,
};

const here = dirname(fileURLToPath(import.meta.url));
const dest = join(here, '..', '..', 'sdk', 'python', 'tests', 'vectors.json');
writeFileSync(dest, `${JSON.stringify(out, null, 2)}\n`);
process.stdout.write(
  `wrote ${canon.length} canonical + ${descriptors.length} descriptor vectors\n`,
);
