"""Cross-language conformance: the TypeScript implementation is the reference.

These assert byte equality against vectors generated by
``contracts/scripts/gen-vectors.mjs``. A Python-only test of canonicalization
would pass happily while producing output the hub rejects, which is the
failure mode that matters.
"""

from __future__ import annotations

import json
import unittest
from pathlib import Path

from agentbridge.canonical import CanonicalizationError, canonicalize
from agentbridge.signing import payload_hash, request_descriptor, sha256_hex, sign_descriptor

VECTORS = json.loads((Path(__file__).parent / "vectors.json").read_text(encoding="utf-8"))


class TestCanonicalVectors(unittest.TestCase):
    def test_matches_typescript_byte_for_byte(self) -> None:
        for case in VECTORS["canonical"]:
            with self.subTest(case["name"]):
                self.assertEqual(canonicalize(case["value"]), case["canonical"])

    def test_payload_hash_matches_typescript(self) -> None:
        for case in VECTORS["canonical"]:
            with self.subTest(case["name"]):
                self.assertEqual(payload_hash(case["value"]), case["payload_hash"])

    def test_sha256_matches_typescript(self) -> None:
        for case in VECTORS["sha256"]:
            with self.subTest(case["input"]):
                self.assertEqual(sha256_hex(case["input"]), case["hex"])


class TestCanonicalRules(unittest.TestCase):
    def test_sorts_keys_by_utf16_code_unit_not_code_point(self) -> None:
        # The divergence a naive sorted() introduces: an astral character
        # begins with a 0xD800 surrogate, so it precedes U+FFFF in UTF-16 and
        # follows it by code point.
        out = canonicalize({"￿": 1, "\U00010000": 2})
        self.assertLess(out.index("\U00010000"), out.index("￿"))

    def test_does_not_normalize_unicode(self) -> None:
        # Normalizing would alter an agent's content underneath its signature.
        self.assertNotEqual(canonicalize({"a": "é"}), canonicalize({"a": "é"}))

    def test_is_insensitive_to_insertion_order(self) -> None:
        self.assertEqual(canonicalize({"b": 1, "a": 2}), canonicalize({"a": 2, "b": 1}))

    def test_writes_an_integral_float_without_a_fraction(self) -> None:
        self.assertEqual(canonicalize({"n": 1.0}), '{"n":1}')

    def test_refuses_a_non_finite_number(self) -> None:
        for bad in (float("nan"), float("inf"), float("-inf")):
            with self.assertRaises(CanonicalizationError):
                canonicalize({"n": bad})

    def test_refuses_an_integer_javascript_cannot_hold_exactly(self) -> None:
        # Silently truncating would make the two sides disagree about the
        # value, not merely its spelling.
        with self.assertRaises(CanonicalizationError):
            canonicalize({"n": 2**53})

    def test_refuses_an_unpaired_surrogate(self) -> None:
        with self.assertRaises(CanonicalizationError):
            canonicalize({"s": "\ud800"})

    def test_refuses_a_value_with_no_json_form(self) -> None:
        with self.assertRaises(CanonicalizationError):
            canonicalize({"s": object()})


class TestSigningVectors(unittest.TestCase):
    def test_request_descriptor_matches_typescript(self) -> None:
        for case in VECTORS["descriptors"]:
            with self.subTest(case["name"]):
                self.assertEqual(
                    request_descriptor(
                        method=case["method"],
                        path=case["path"],
                        query=case["query"],
                        body=case["body"],
                        timestamp=case["timestamp"],
                    ),
                    case["descriptor"],
                )

    def test_signature_is_byte_identical_to_typescript(self) -> None:
        # Ed25519 is deterministic, so the same key over the same bytes must
        # give the same signature. Merely "verifies" would hide an encoder
        # difference that only shows up for some payloads.
        import base64

        priv = base64.b64decode(VECTORS["privateKeyBase64"])
        for case in VECTORS["descriptors"]:
            with self.subTest(case["name"]):
                self.assertEqual(sign_descriptor(case["descriptor"], priv), case["signature"])


if __name__ == "__main__":
    unittest.main()
